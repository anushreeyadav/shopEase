"""Write the implemented database schema into docs/database_ownership.md (generated section).

    python scripts/export_schema.py

Reads each service's own SQLAlchemy metadata and Alembic head (each in its own process,
because every package is named `app`). No database connection is needed.
"""

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SERVICES = {"auth_service": "auth_db", "user_service": "user_db", "product_service": "product_db",
            "order_service": "order_db", "payment_service": "payment_db"}
START, END = "<!-- implemented-schema:start -->", "<!-- implemented-schema:end -->"
DUMP = r'''
import json, sys
from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy.dialects import mysql
from app.models import Base
dialect = mysql.dialect()
tables = []
for table in Base.metadata.sorted_tables:
    columns = [{"name": c.name, "type": str(c.type.compile(dialect=dialect)), "nullable": c.nullable,
                "pk": c.primary_key, "fk": [f.target_fullname for f in c.foreign_keys]} for c in table.columns]
    uniques = [list(c.columns.keys()) for c in table.constraints if c.__class__.__name__ == "UniqueConstraint"]
    uniques += [[c.name for c in i.columns] for i in table.indexes if i.unique]
    checks = sorted(str(c.name) for c in table.constraints if c.__class__.__name__ == "CheckConstraint")
    indexes = [[c.name for c in i.columns] for i in table.indexes if not i.unique]
    tables.append({"name": table.name, "columns": columns, "unique": uniques, "checks": checks, "indexes": indexes})
script = ScriptDirectory.from_config(Config("alembic.ini"))
revisions = [r.revision for r in script.walk_revisions()][::-1]
sys.stdout.write("@@" + json.dumps({"tables": tables, "revisions": revisions}))
'''


def main() -> int:
    lines = [START, "", "## As Implemented (generated)", "",
             "Generated by `python scripts/export_schema.py` from the models and migrations. MySQL types",
             "as created by the migrations. **FK** = foreign key inside the same database; columns",
             "marked *external* hold another service's ID and have no foreign key.", ""]
    lines += ["| Database | Owner | Tables | Migrations (in order) | Migrate |",
              "|----------|-------|--------|-----------------------|---------|"]
    sections = []
    for service, database in SERVICES.items():
        result = subprocess.run([sys.executable, "-c", DUMP], cwd=ROOT / "services" / service, check=True,
                                capture_output=True, text=True, env={**os.environ, "LOG_LEVEL": "WARNING"})
        data = json.loads(result.stdout.split("@@", 1)[1])
        lines.append(f"| `{database}` | {service} | {len(data['tables'])} | {', '.join(data['revisions'])} | "
                     f"`docker compose run --rm {service.replace('_service', '')}_migrate` |")
        sections += ["", f"### `{database}` ({service})", ""]
        for table in data["tables"]:
            sections += [f"**`{table['name']}`**", "", "| Column | Type | Null | Key |", "|--------|------|------|-----|"]
            for c in table["columns"]:
                key = "PK" if c["pk"] else ""
                if c["fk"]:
                    key = (key + " " if key else "") + "FK → " + ", ".join(f"`{t}`" for t in c["fk"])
                elif c["name"].endswith("_id") and not c["pk"] and c["name"] not in ("client_id",):
                    key = (key + " " if key else "") + "*external*"
                sections.append(f"| `{c['name']}` | {c['type']} | {'yes' if c['nullable'] else 'no'} | {key} |")
            extras = []
            if table["unique"]:
                extras.append("unique: " + "; ".join("(" + ", ".join(u) + ")" for u in table["unique"]))
            if table["indexes"]:
                extras.append("indexes: " + "; ".join("(" + ", ".join(i) + ")" for i in table["indexes"]))
            if table["checks"]:
                extras.append("checks: " + ", ".join(f"`{c}`" for c in table["checks"]))
            sections += ["", "; ".join(extras), ""] if extras else [""]
    lines += sections + ["", "Migration commands: [database_setup.md](database_setup.md) and "
                         "[local_development.md](local_development.md) §4.", "", END]

    doc = ROOT / "docs" / "database_ownership.md"
    text = doc.read_text(encoding="utf-8")
    block = "\n".join(lines)
    if START in text:
        text = text[:text.index(START)] + block + text[text.index(END) + len(END):]
    else:
        anchor = "## Validation Checklist"
        text = text.replace(anchor, block + "\n\n---\n\n" + anchor, 1)
    doc.write_text(text, encoding="utf-8", newline="\n")
    print("docs/database_ownership.md: implemented schema section written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
