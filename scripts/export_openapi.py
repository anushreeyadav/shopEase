"""Export every component's OpenAPI schema and generate docs/api_reference.md from them.

    python scripts/export_openapi.py

Writes docs/openapi/<component>.json (importable into Postman, Swagger Editor, client
generators) and docs/api_reference.md (one table of every endpoint). Each component is loaded
in its own process because every package is named `app`. No service needs to be running.
"""

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPONENTS = {
    "api_gateway": ("api_gateway", 8000),
    "auth_service": ("services/auth_service", 8001),
    "user_service": ("services/user_service", 8002),
    "product_service": ("services/product_service", 8003),
    "order_service": ("services/order_service", 8004),
    "payment_service": ("services/payment_service", 8005),
}
DUMP = "import json, sys; from app.main import app; sys.stdout.write('@@' + json.dumps(app.openapi()))"


def load(path: str) -> dict:
    result = subprocess.run([sys.executable, "-c", DUMP], cwd=ROOT / path, capture_output=True, text=True,
                            env={**os.environ, "APP_ENV": "test", "LOG_LEVEL": "WARNING"}, check=True)
    return json.loads(result.stdout.split("@@", 1)[1])


def access(operation: dict) -> str:
    security = operation.get("security")
    if not security:
        return "Public"
    if {} in security:
        return "Public (token optional)"
    scheme = next(iter(security[0]))
    if scheme == "serviceToken":
        return "Service token"
    return "Token + role check" if "403" in operation["responses"] else "Token"


def main() -> int:
    out = ROOT / "docs" / "openapi"
    out.mkdir(parents=True, exist_ok=True)
    rows, counts = [], {}
    for name, (path, port) in COMPONENTS.items():
        schema = load(path)
        (out / f"{name}.json").write_text(json.dumps(schema, indent=2) + "\n", encoding="utf-8", newline="\n")
        counts[name] = 0
        for route, item in schema["paths"].items():
            for method, operation in item.items():
                counts[name] += 1
                success = ", ".join(c for c in operation["responses"] if c.startswith("2"))
                rows.append((name, port, method.upper(), route, operation.get("summary", ""), access(operation), success))

    lines = [
        "# API Reference",
        "",
        "Generated by `python scripts/export_openapi.py` from the services' own OpenAPI schemas. Do not edit",
        "by hand: change the code and regenerate. Full schemas (request/response models, examples,",
        "error responses): `docs/openapi/<component>.json`, or Swagger UI at `http://127.0.0.1:<port>/docs`",
        "while the stack runs. Clients use the gateway (`http://127.0.0.1:8000`) with the same `/api/...`",
        "paths; `/internal/...` routes are service-to-service only and are not routed by the gateway.",
        "",
        "Every error uses the ShopEase envelope `{\"error\": {\"code\", \"message\", \"details\"?, \"request_id\"}}`.",
        "Access: **Token** = user access token (`Authorization: Bearer`), **Token + role check** = also needs",
        "the admin role or a scope (else `403`), **Service token** = internal client-credentials token.",
        "Ownership (only your own orders, payments, addresses) is enforced inside each service.",
        "",
        "| Component | Port | Swagger UI | OpenAPI file | Operations |",
        "|-----------|------|------------|--------------|-----------:|",
    ]
    for name, (path, port) in COMPONENTS.items():
        lines.append(f"| {name} | {port} | http://127.0.0.1:{port}/docs | [openapi/{name}.json](openapi/{name}.json) | {counts[name]} |")
    current = None
    for name, port, method, route, summary, who, success in rows:
        if name != current:
            current = name
            lines += ["", f"## {name}", "", "| Method | Path | Summary | Access | Success |", "|--------|------|---------|--------|---------|"]
        lines.append(f"| {method} | `{route}` | {summary} | {who} | {success} |")
    (ROOT / "docs" / "api_reference.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Exported {len(COMPONENTS)} schemas and {len(rows)} operations to docs/openapi/ and docs/api_reference.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
