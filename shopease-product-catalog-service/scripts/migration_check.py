"""Check the Alembic migrations against a real MySQL 8 server.

Two modes:

  Read-only verification of any allowed database (changes nothing):
      python -m scripts.migration_check --verify-only

  Full cycle on the THROWAWAY test database only (upgrade, downgrade to base, upgrade again,
  constraint probes, alembic check). It drops and recreates the catalog tables, so it refuses
  to run unless MYSQL_DATABASE is shopease_product_catalog_test_db:
      $env:MYSQL_DATABASE="shopease_product_catalog_test_db"; python -m scripts.migration_check

Every line printed is the result of a query or command actually executed. The exit code is 0
only if every check passed.
"""

import argparse
import sys
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import text
from sqlalchemy.exc import DBAPIError

from app.core.config import get_settings
from app.database.connection import engine

PROJECT_ROOT = Path(__file__).resolve().parent.parent
TEST_DATABASE = "shopease_product_catalog_test_db"
TABLES = ("categories", "products", "inventory_transactions")

EXPECTED = {
    "primary keys": {("categories", "PRIMARY"), ("products", "PRIMARY"), ("inventory_transactions", "PRIMARY")},
    "unique": {("categories", "uq_categories_name"), ("products", "uq_products_sku")},
    "foreign keys": {
        ("products", "fk_products_category_id_categories", "categories", "RESTRICT"),
        ("inventory_transactions", "fk_inventory_transactions_product_id_products", "products", "RESTRICT"),
    },
    "checks": {
        ("categories", "ck_categories_name_not_blank"),
        ("products", "ck_products_price_non_negative"),
        ("products", "ck_products_discount_price_valid"),
        ("products", "ck_products_stock_quantity_non_negative"),
        ("products", "ck_products_name_not_blank"),
        ("products", "ck_products_sku_not_blank"),
        ("inventory_transactions", "ck_inventory_transactions_quantity_positive"),
        ("inventory_transactions", "ck_inventory_transactions_previous_stock_non_negative"),
        ("inventory_transactions", "ck_inventory_transactions_updated_stock_non_negative"),
        ("inventory_transactions", "ck_inventory_transactions_stock_arithmetic"),
        ("inventory_transactions", "ck_inventory_transactions_transaction_type"),
    },
    "indexes": {
        ("products", "ix_products_name", "name"),
        ("products", "ix_products_category_id", "category_id"),
        ("products", "ix_products_price", "price"),
        ("products", "ix_products_created_at", "created_at"),
        ("products", "uq_products_sku", "sku"),
        ("categories", "uq_categories_name", "name"),
        ("inventory_transactions", "ix_inventory_transactions_product_id_created_at", "product_id,created_at"),
    },
}

failures: list[str] = []


def report(ok: bool, message: str) -> None:
    print(f"[{'PASS' if ok else 'FAIL'}] {message}")
    if not ok:
        failures.append(message)


def alembic_config() -> Config:
    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(PROJECT_ROOT / "alembic"))
    return config


def query(sql: str, **params):
    with engine.connect() as conn:
        return conn.execute(text(sql), params).all()


def schema_snapshot(database: str) -> dict[str, set]:
    rows = query("SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE FROM information_schema.TABLE_CONSTRAINTS "
                 "WHERE TABLE_SCHEMA = :db", db=database)
    by_type: dict[str, set] = {}
    for table, name, kind in rows:
        by_type.setdefault(kind, set()).add((table, name))
    fks = query("SELECT TABLE_NAME, CONSTRAINT_NAME, REFERENCED_TABLE_NAME, DELETE_RULE "
                "FROM information_schema.REFERENTIAL_CONSTRAINTS WHERE CONSTRAINT_SCHEMA = :db", db=database)
    indexes = query("SELECT TABLE_NAME, INDEX_NAME, GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX) "
                    "FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = :db "
                    "GROUP BY TABLE_NAME, INDEX_NAME", db=database)
    return {
        "primary keys": by_type.get("PRIMARY KEY", set()),
        "unique": by_type.get("UNIQUE", set()),
        "checks": by_type.get("CHECK", set()),
        "foreign keys": {tuple(r) for r in fks},
        "indexes": {tuple(r) for r in indexes},
    }


def existing_tables(database: str) -> set[str]:
    return {r[0] for r in query("SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA = :db", db=database)}


def verify_schema(database: str) -> None:
    tables = existing_tables(database)
    report(set(TABLES) <= tables, f"tables present: {sorted(tables & set(TABLES))}")
    version = query("SELECT version_num FROM alembic_version") if "alembic_version" in tables else []
    report([r[0] for r in version] == ["c4a7d2e91b30"], f"alembic_version = {[r[0] for r in version]}")

    snapshot = schema_snapshot(database)
    for kind, expected in EXPECTED.items():
        missing = expected - snapshot[kind]
        report(not missing, f"{kind}: {len(expected) - len(missing)}/{len(expected)} expected present"
               + (f"; missing {sorted(missing)}" if missing else ""))

    for table in TABLES:
        columns = [r[0] for r in query(
            "SELECT COLUMN_NAME FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = :db AND TABLE_NAME = :t "
            "ORDER BY ORDINAL_POSITION", db=database, t=table)]
        print(f"       {table}: {', '.join(columns)}")
    engine_rows = query(
        "SELECT TABLE_NAME, ENGINE, TABLE_COLLATION FROM information_schema.TABLES WHERE TABLE_SCHEMA = :db "
        "AND TABLE_NAME IN ('categories', 'products', 'inventory_transactions')", db=database)
    report(all(r[1] == "InnoDB" for r in engine_rows) and len(engine_rows) == 3,
           "storage engine InnoDB (required for foreign keys and transactions): "
           + ", ".join(f"{r[0]}={r[1]}/{r[2]}" for r in sorted(engine_rows)))

    try:
        command.check(alembic_config())
        report(True, "alembic check: models and database match")
    except AutogenerateDiffsDetected as exc:
        report(False, f"alembic check found differences: {exc}")


def probe_constraints() -> None:
    """Try invalid rows inside one transaction that is always rolled back."""
    probes = [
        ("negative stock_quantity", 3819,
         "INSERT INTO products (category_id, name, sku, price, stock_quantity) VALUES (:cid, 'P', 'NEG', 1, -1)"),
        ("discount_price >= price", 3819,
         "INSERT INTO products (category_id, name, sku, price, discount_price) VALUES (:cid, 'P', 'DSC', 10, 10)"),
        ("negative price", 3819,
         "INSERT INTO products (category_id, name, sku, price) VALUES (:cid, 'P', 'NPR', -1)"),
        ("duplicate SKU", 1062,
         "INSERT INTO products (category_id, name, sku, price) VALUES (:cid, 'P', 'PROBE-1', 1)"),
        ("duplicate category name", 1062, "INSERT INTO categories (name) VALUES ('Probe Category')"),
        ("product with unknown category", 1452,
         "INSERT INTO products (category_id, name, sku, price) VALUES (2147483647, 'P', 'FK', 1)"),
        ("transaction type other than IN/OUT", 3819,
         "INSERT INTO inventory_transactions (product_id, transaction_type, quantity, previous_stock, updated_stock) "
         "VALUES (:pid, 'MOV', 1, 0, 1)"),
        ("transaction arithmetic wrong", 3819,
         "INSERT INTO inventory_transactions (product_id, transaction_type, quantity, previous_stock, updated_stock) "
         "VALUES (:pid, 'IN', 5, 0, 4)"),
        ("transaction with zero quantity", 3819,
         "INSERT INTO inventory_transactions (product_id, transaction_type, quantity, previous_stock, updated_stock) "
         "VALUES (:pid, 'IN', 0, 0, 0)"),
        ("delete category that has products", 1451, "DELETE FROM categories WHERE id = :cid"),
    ]
    with engine.connect() as conn:
        outer = conn.begin()
        try:
            conn.execute(text("INSERT INTO categories (name) VALUES ('Probe Category')"))
            cid = conn.execute(text("SELECT id FROM categories WHERE name = 'Probe Category'")).scalar()
            conn.execute(text("INSERT INTO products (category_id, name, sku, price) VALUES (:cid, 'Probe', 'PROBE-1', 5)"),
                         {"cid": cid})
            pid = conn.execute(text("SELECT id FROM products WHERE sku = 'PROBE-1'")).scalar()
            conn.execute(text("INSERT INTO inventory_transactions (product_id, transaction_type, quantity, "
                              "previous_stock, updated_stock) VALUES (:pid, 'IN', 3, 0, 3)"), {"pid": pid})
            report(True, "valid category, product and IN transaction accepted")
            created = conn.execute(text("SELECT created_at FROM categories WHERE id = :cid"), {"cid": cid}).scalar()
            utc_now = conn.execute(text("SELECT UTC_TIMESTAMP()")).scalar()
            report(abs((utc_now - created).total_seconds()) < 60,
                   f"server default created_at is UTC ({created} vs UTC_TIMESTAMP() {utc_now})")

            for label, expected_code, sql in probes:
                savepoint = conn.begin_nested()
                try:
                    conn.execute(text(sql), {"cid": cid, "pid": pid})
                    savepoint.rollback()
                    report(False, f"{label}: accepted, but should have been refused")
                except DBAPIError as exc:
                    savepoint.rollback()
                    code = exc.orig.args[0] if exc.orig is not None and exc.orig.args else None
                    report(code == expected_code, f"{label}: refused by MySQL with error {code}")
        finally:
            outer.rollback()
    leftovers = query("SELECT COUNT(*) FROM categories WHERE name = 'Probe Category'")[0][0]
    report(leftovers == 0, "probe rows rolled back (none left behind)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--verify-only", action="store_true", help="inspect the configured database; change nothing")
    args = parser.parse_args()

    settings = get_settings()
    database = query("SELECT DATABASE()")[0][0]
    version = query("SELECT VERSION()")[0][0]
    print(f"MySQL server {version} at {settings.mysql_host}:{settings.mysql_port}, database {database}")
    report(version.split(".")[0] == "8", f"server is MySQL 8 ({version})")

    if args.verify_only:
        verify_schema(database)
    else:
        if database != TEST_DATABASE:
            print(f"Refusing: the full cycle drops tables and runs only on {TEST_DATABASE}, not {database}.")
            return 2
        config = alembic_config()
        print("\n== alembic upgrade head")
        command.upgrade(config, "head")
        verify_schema(database)

        print("\n== alembic downgrade base")
        command.downgrade(config, "base")
        remaining = existing_tables(database) & set(TABLES)
        report(not remaining, f"after downgrade, catalog tables left: {sorted(remaining)}")
        report(query("SELECT COUNT(*) FROM alembic_version")[0][0] == 0, "alembic_version is empty after downgrade")

        print("\n== alembic upgrade head (again)")
        command.upgrade(config, "head")
        verify_schema(database)

        print("\n== constraint probes (one transaction, rolled back)")
        probe_constraints()

    print(f"\n{'ALL CHECKS PASSED' if not failures else f'{len(failures)} CHECK(S) FAILED'}")
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
