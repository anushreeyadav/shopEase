def request(name, method, url, body=None, status=200, extra_tests=(), no_auth=False, prerequest=()):
    tests = [f'pm.test("status is {status}", () => pm.response.to.have.status({status}));', *extra_tests]
    item = {
        "name": name,
        "event": [{"listen": "test", "script": {"type": "text/javascript", "exec": tests}}],
        "request": {"method": method, "header": [], "url": url},
    }
    if prerequest:
        item["event"].insert(0, {"listen": "prerequest", "script": {"type": "text/javascript", "exec": list(prerequest)}})
    if body is not None:
        item["request"]["header"].append({"key": "Content-Type", "value": "application/json"})
        item["request"]["body"] = {"mode": "raw", "raw": json.dumps(body, indent=2)}
    if no_auth:
        item["request"]["auth"] = {"type": "noauth"}
    return item


